# Display names of the load cases, as used in the thesis. The file and key
# names keep the short codes (LC1_Maneuver, LC3_Combined, LC7_Emergency).
import re as _re
_FORMAL = [(r'\bLC7 Emergency\b', 'emergency landing'), (r'\bLC1 Maneuver\b', 'symmetric manoeuvre'),
           (r'\bLC3 Combined\b', 'combined manoeuvre'), (r'\bLC1\b', 'Symmetric manoeuvre'),
           (r'\bLC3\b', 'Combined manoeuvre'), (r'\bLC7\b', 'Emergency landing')]


def formal(text):
    for pat, rep in _FORMAL:
        text = _re.sub(pat, rep, text)
    return text

DOCS = os.path.join(RP.REPO, 'docs')
os.makedirs(DOCS, exist_ok=True)
AC = ['E190', 'A320', 'A350']
NAME = {'E190': 'E190', 'A320': 'A320', 'A350': 'A350-900'}
LCS = ['Baseline', 'LC1_Maneuver', 'LC3_Combined', 'LC7_Emergency']
LCN = {'Baseline': 'Baseline', 'LC1_Maneuver': 'LC1', 'LC3_Combined': 'LC3', 'LC7_Emergency': 'LC7'}
FILLS = ['0.10', '0.30', '0.50', '0.75', '0.90']


def f(x, n=3):
    return '-' if x is None else ('%.*f' % (n, x))


# ------------------------------------------------------------ full matrices
L = ['# Complete results matrices', '',
     'All 120 cases of the revised report: three tanks, four load cases, five fill levels, solved at',
     '1.5 bar (strength) and at 0.187 bar (stability), at the sized walls, production mesh.',
     'Generated by `code/3_results_processing/make_review_docs.py` from `results/processed/final_numbers.json`.', '',
     'Columns: dT = wetted-to-dry temperature difference; s_vM = far-field von Mises stress (largest value',
     'more than 0.5 m from every ring); RF_y = (F_ty/1.5)/s_vM with F_ty/1.5 = 262 MPa; u_max = maximum',
     'displacement; R = total ring reaction; s_x,min = most compressive axial membrane stress of the far-field',
     'barrel at 0.187 bar; RF_b = (s_cr/1.5)/|s_x,min|, a dash where the barrel is in tension.', '',
     'The material properties are room-temperature values (alpha = 22.3e-6 /K, kappa = 116 W/mK); see',
     '`detailed_calculations.md` for the cryogenic corrections.', '']
for ac in AC:
    d = D[ac]
    scr = d['sigma_cr_MPa']
    L += ['## %s, wall %.3f mm, sigma_cr = %.2f MPa' % (NAME[ac], d['t_wall_mm'], scr), '',
          '| Case | fill | dT [K] | s_vM [MPa] | RF_y | u_max [mm] | R [kN] | s_x,min [MPa] | RF_b |',
          '|---|---|---|---|---|---|---|---|---|']
    for lc in LCS:
        for fl in FILLS:
            p = d['production']['%s|%s' % (lc, fl)]
            s = d['stability']['%s|%s' % (lc, fl)]
            ax = s['axial_mem_min_MPa']
            rfb = (scr / 1.5) / -ax if ax < 0 else None
            L.append('| %s | %s | %.3f | %.1f | %.3f | %.2f | %.1f | %.2f | %s |' % (
                LCN[lc], fl, p['dT'], p['mises_MPa'], 262.0 / p['mises_MPa'], p['u_max_mm'],
                p['sumRF_N'] / 1e3, ax, f(rfb)))
    L.append('')
open(os.path.join(DOCS, 'full_results_matrices.md'), 'w').write(formal('\n'.join(L)) + '\n')

