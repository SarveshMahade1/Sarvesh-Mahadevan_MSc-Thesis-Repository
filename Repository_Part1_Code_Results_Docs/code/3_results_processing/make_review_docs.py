def row(label, key_fn, n=3):
    return '| %s | %s |' % (label, ' | '.join(f(key_fn(ac), n) for ac in AC))


def table(title, rows, note=None):
    out = ['## ' + title, '']
    if note:
        out += [note, '']
    out += ['| Quantity | E190 | A320 | A350-900 |', '|---|---|---|---|'] + rows + ['']
    return out


